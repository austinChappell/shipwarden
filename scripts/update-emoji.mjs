// Writes src/shared/emoji-shortcodes.ts from the emoji list of GitHub (GET https://api.github.com/emojis).
// Run it again when GitHub adds emoji: node scripts/update-emoji.mjs
import { writeFileSync } from 'node:fs';

const response = await fetch('https://api.github.com/emojis', { headers: { Accept: 'application/vnd.github+json' } });
if (!response.ok) {
    throw new Error(`GitHub returned ${response.status} for the emoji list.`);
}
const list = await response.json();

const map = {};
for (const [name, url] of Object.entries(list)) {
    // A Unicode emoji has its code points in the file name, for example ".../unicode/1f1fa-1f1f8.png".
    // A custom emoji of GitHub, for example :shipit:, is only an image. The map does not have it.
    const match = /\/unicode\/([0-9a-f-]+)\.png/.exec(url);
    if (!match) continue;
    const points = match[1].split('-').map(hex => parseInt(hex, 16));
    // A single code point below U+1F000, for example U+26A0 (warning), shows as text without the emoji variation selector.
    if (points.length === 1 && points[0] < 0x1f000) points.push(0xfe0f);
    map[name] = String.fromCodePoint(...points);
}

const lines = Object.entries(map)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, emoji]) => `    ${JSON.stringify(name)}: ${JSON.stringify(emoji)},`);
const file = `// This file is generated by scripts/update-emoji.mjs from the emoji list of GitHub. Do not edit it.

/** The Unicode emoji of GitHub by shortcode, for example "white_check_mark" → "✅". */
export const EMOJI_SHORTCODES: Readonly<Record<string, string>> = {
${lines.join('\n')}
};
`;
writeFileSync(new URL('../src/shared/emoji-shortcodes.ts', import.meta.url), file);
console.log(`Wrote ${lines.length} emoji.`);
